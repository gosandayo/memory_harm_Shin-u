"""Phase D-1b interactive Claude relay runner for P16 sessions.

This runner automates the manual relay pattern:

  1. Claude CLI acts as the live operator for one run.
  2. Claude outputs one JSON operator decision.
  3. The runner sends `next_user_message` to the target OpenAI chat model.
  4. The runner logs the target response and relays it back to Claude.
  5. Repeat until Claude stops, the target reaches P16/R4, or turn budget ends.

The target API is used only for target-assistant responses. Claude is accessed
through the local Claude CLI as the operator. No target response is generated by
Claude, and no user prompt is generated by the OpenAI target API.

Artifacts:
  session_meta.yaml
  messages.jsonl
  operator_trace.jsonl
  adaptive_trace.jsonl
  stage_events.jsonl
  annotations.yaml
  user-side replay YAML on finish
"""

